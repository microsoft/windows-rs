use std::fmt::Write;
use std::path::Path;

const WINDOWS_WINMD: &str = "../../libs/default/Windows.winmd";

fn main() {
    println!("cargo:rerun-if-changed=fixtures");
    println!("cargo:rerun-if-changed={WINDOWS_WINMD}");
    println!(
        "cargo:rustc-env=TARGET={}",
        std::env::var("TARGET").unwrap()
    );

    let out = std::env::var("OUT_DIR").unwrap();
    let out = Path::new(&out);
    let fixtures = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("fixtures");

    let mut names: Vec<_> = std::fs::read_dir(&fixtures)
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.is_dir())
        .map(|path| path.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    names.sort();

    let mut bindgen = windows_bindgen::builder();
    // Bindgen only generates filtered types, so include the Windows types that fixtures reference.
    bindgen
        .input_default()
        .output(out.join("bindings.rs"))
        .filter("Windows.Foundation.EventHandler")
        .filter("Windows.Foundation.IClosable")
        .filter("Windows.Foundation.IReferenceArray")
        .filter("Windows.Foundation.IStringable")
        .filter("Windows.Foundation.Numerics")
        .filter("Windows.Foundation.PropertyValue")
        .filter("Windows.Foundation.TypedEventHandler")
        .filter("Windows.Foundation.Uri")
        .implement_all();

    // The Win32 APIs that the component and the Rust consumer use.
    windows_bindgen::builder()
        .input_default()
        .output(out.join("win32.rs"))
        .flat()
        .filter("IActivationFactory")
        .filter("IAgileObject")
        .filter("AddDllDirectory")
        .filter("CLASS_E_CLASSNOTAVAILABLE")
        .filter("CoInitializeEx")
        .filter("CoUninitialize")
        .filter("COINIT_APARTMENTTHREADED")
        .filter("COINIT_MULTITHREADED")
        .filter("CLASS_E_NOAGGREGATION")
        .filter("E_BOUNDS")
        .filter("E_FAIL")
        .filter("E_INVALIDARG")
        .filter("E_NOINTERFACE")
        .filter("E_NOTIMPL")
        .filter("E_POINTER")
        .filter("GetCurrentThreadId")
        .filter("REGDB_E_CLASSNOTREG")
        .filter("S_OK")
        .implement_all()
        .write();

    let mut tests = String::from("// @generated by build.rs\n");
    let mut modules = String::from("// @generated by build.rs\n");
    let mut factory = String::from(
        "fn fixture_factory(name: &str) -> Option<IActivationFactory> {\n    match name.split('.').next()? {\n",
    );
    let mut clients = String::from("// @generated by build.rs\n");
    let mut client = String::from(
        "fn fixture_client(name: &str) -> Option<fn() -> Result<()>> {\n    match name {\n",
    );

    for name in &names {
        assert!(
            name.starts_with(|c: char| c.is_ascii_lowercase())
                && name
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "fixture `{name}` must be a lowercase snake_case name"
        );

        let namespace = namespace(name);
        let winmd = out.join(format!("{name}.winmd"));

        windows_rdl::reader()
            .input(fixtures.join(name).join("api.rdl"))
            .output(&winmd)
            .reference_default()
            .write()
            .unwrap_or_else(|e| panic!("fixture `{name}`: {e}"));

        bindgen.input(&winmd).filter(&namespace);

        writeln!(
            tests,
            "#[test]\nfn {name}() {{ run({name:?}, {namespace:?}); }}"
        )
        .unwrap();

        let component = fixtures.join(name).join("component.rs");

        if component.is_file() {
            writeln!(modules, "#[path = {:?}]\nmod {name};", component.display()).unwrap();
            writeln!(factory, "        {namespace:?} => {name}::factory(name),").unwrap();
        }

        let rust_client = fixtures.join(name).join("client.rs");

        if rust_client.is_file() {
            writeln!(
                clients,
                "#[path = {:?}]\nmod {name};",
                rust_client.display()
            )
            .unwrap();
            writeln!(client, "        {name:?} => Some({name}::test),").unwrap();
        }
    }

    factory.push_str("        _ => None,\n    }\n}\n");
    modules.push_str(&factory);
    client.push_str("        _ => None,\n    }\n}\n");
    clients.push_str(&client);

    bindgen.write();
    std::fs::write(out.join("fixtures.rs"), tests).unwrap();
    std::fs::write(out.join("component.rs"), modules).unwrap();
    std::fs::write(out.join("client.rs"), clients).unwrap();

    // Every fixture projection references the Windows namespaces, so generate them once. The tests'
    // nested component build only needs the Rust bindings.
    println!("cargo:rerun-if-env-changed=TEST_WINRT_INTEROP_COMPONENT");
    if cfg!(windows)
        && std::env::var("CARGO_CFG_TARGET_ENV").unwrap() == "msvc"
        && std::env::var_os("TEST_WINRT_INTEROP_COMPONENT").is_none()
    {
        cppwinrt::cppwinrt([
            "-in",
            WINDOWS_WINMD,
            "-out",
            out.join("cppwinrt").to_str().unwrap(),
        ]);
    }
}

/// The namespace a fixture must use: its name in PascalCase, so `event_generic` is `EventGeneric`.
fn namespace(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + chars.as_str()
            })
        })
        .collect()
}
