use std::path::Path;

const WINDOWS_WINMD: &str = "../../../libs/default/Windows.winmd";

fn main() {
    println!("cargo:rerun-if-changed=fixtures");
    println!("cargo:rerun-if-changed={WINDOWS_WINMD}");
    println!(
        "cargo:rustc-env=TARGET={}",
        std::env::var("TARGET").unwrap()
    );

    let out = std::env::var("OUT_DIR").unwrap();
    let out = Path::new(&out);

    let mut names: Vec<_> = std::fs::read_dir("fixtures")
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.is_dir())
        .map(|path| path.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    names.sort();

    let mut tests = String::from("// @generated by build.rs\n");

    for name in names {
        assert!(
            name.starts_with(|c: char| c.is_ascii_lowercase())
                && name
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "fixture `{name}` must be a lowercase snake_case name"
        );
        tests.push_str(&format!("#[test]\nfn {name}() {{ run({name:?}); }}\n"));
    }

    std::fs::write(out.join("fixtures.rs"), tests).unwrap();

    // Every fixture projection references the Windows namespaces, so generate them once.
    if cfg!(windows) && std::env::var("CARGO_CFG_TARGET_ENV").unwrap() == "msvc" {
        cppwinrt::cppwinrt([
            "-in",
            WINDOWS_WINMD,
            "-out",
            out.join("cppwinrt").to_str().unwrap(),
        ]);
    }
}
