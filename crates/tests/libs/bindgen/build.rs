use std::path::Path;

fn rust_ident(name: &str) -> String {
    let ident = name.replace('-', "_");
    match ident.as_str() {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct" | "super"
        | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await"
        | "dyn" | "abstract" | "become" | "box" | "do" | "final" | "macro" | "override"
        | "priv" | "typeof" | "unsized" | "virtual" | "yield" | "try" => format!("r#{ident}"),
        _ => ident,
    }
}

fn main() {
    println!("cargo:rerun-if-changed=input");
    println!("cargo:rerun-if-changed=expected");
    println!("cargo:rerun-if-changed=src/abi_exports.rs");

    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).to_path_buf();
    std::fs::create_dir_all(&out).unwrap();

    // Miri calls the same exports compiled into the test binary instead of loading a DLL.
    if std::env::var_os("CARGO_CFG_WINDOWS").is_some()
        && std::env::var_os("CARGO_CFG_MIRI").is_none()
    {
        let status = std::process::Command::new(std::env::var_os("RUSTC").unwrap())
            .args([
                "--crate-name",
                "bindgen_abi",
                "--crate-type",
                "cdylib",
                "--edition=2024",
                "-Dwarnings",
                "--target",
            ])
            .arg(std::env::var_os("TARGET").unwrap())
            .arg("src/abi_exports.rs")
            .arg("--out-dir")
            .arg(&out)
            .status()
            .unwrap();
        assert!(status.success(), "failed to build the ABI fixture DLL");
        println!("cargo:rustc-link-search=native={}", out.display());
    }

    let input_dir = Path::new("input");
    let mut tests = String::from("// @generated by build.rs\n");

    if input_dir.is_dir() {
        let mut entries: Vec<_> = std::fs::read_dir(input_dir)
            .unwrap()
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|ext| ext == "rdl"))
            .collect();
        entries.sort();

        for path in &entries {
            let stem = path.file_stem().unwrap().to_string_lossy();
            let ident = rust_ident(&stem);
            tests.push_str(&format!("#[test]\nfn {ident}() {{ run({stem:?}); }}\n"));
        }
    }

    std::fs::write(out.join("generated_tests.rs"), tests).unwrap();

    let expected_dir = Path::new("expected");
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")
        .unwrap()
        .replace('\\', "/");
    let mut modules = String::from("// @generated by build.rs\n");

    if expected_dir.is_dir() {
        let mut entries: Vec<_> = std::fs::read_dir(expected_dir)
            .unwrap()
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|ext| ext == "rs"))
            .collect();
        entries.sort();

        for path in entries {
            let stem = path.file_stem().unwrap().to_string_lossy().to_string();
            let ident = rust_ident(&stem);
            modules.push_str(&format!(
                "#[path = \"{manifest_dir}/expected/{stem}.rs\"]\nmod {ident};\n"
            ));
        }
    }

    std::fs::write(out.join("compile_fixtures.rs"), modules).unwrap();
}
