use std::path::Path;

fn rust_ident(name: &str) -> String {
    assert!(
        name.bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'),
        "fixture name `{name}` is not a valid Rust identifier suffix"
    );
    format!("fixture_{name}")
}

fn main() {
    println!("cargo:rerun-if-changed=input");

    let mut inputs: Vec<_> = std::fs::read_dir("input")
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "h"))
        .collect();
    inputs.sort();

    let mut tests = String::from("// @generated by build.rs\n");
    for input in inputs {
        let name = input.file_stem().unwrap().to_string_lossy();
        let ident = rust_ident(&name);
        tests.push_str(&format!("#[test]\nfn {ident}() {{ run({name:?}); }}\n"));
    }

    std::fs::write(
        Path::new(&std::env::var("OUT_DIR").unwrap()).join("tests.rs"),
        tests,
    )
    .unwrap();
}
