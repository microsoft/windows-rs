use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=input");

    let mut inputs: Vec<_> = std::fs::read_dir("input")
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "h"))
        .collect();
    inputs.sort();

    let mut tests = String::from("// @generated by build.rs\n");
    for input in inputs {
        let name = input.file_stem().unwrap().to_string_lossy();
        let fn_name = escape_keyword(&name);
        tests.push_str(&format!("#[test]\nfn {fn_name}() {{ run({name:?}); }}\n"));
    }

    std::fs::write(
        Path::new(&std::env::var("OUT_DIR").unwrap()).join("tests.rs"),
        tests,
    )
    .unwrap();
}

fn escape_keyword(name: &str) -> String {
    match name {
        "const" | "enum" | "fn" | "struct" | "union" | "unsafe" | "async" | "await" | "impl"
        | "trait" | "type" | "use" | "pub" | "mod" | "crate" | "self" | "super" | "static"
        | "mut" | "ref" | "let" | "if" | "else" | "match" | "loop" | "while" | "for" | "break"
        | "continue" | "return" | "yield" | "where" | "dyn" | "as" | "in" => format!("r#{name}"),
        _ => name.to_string(),
    }
}
