use std::path::Path;

fn rust_ident(name: &str) -> String {
    let ident = name.replace('-', "_");
    match ident.as_str() {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct" | "super"
        | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await"
        | "dyn" | "abstract" | "become" | "box" | "do" | "final" | "macro" | "override"
        | "priv" | "typeof" | "unsized" | "virtual" | "yield" | "try" => format!("r#{ident}"),
        _ => ident,
    }
}

fn main() {
    println!("cargo:rerun-if-changed=input/fixtures");

    let mut entries: Vec<_> = std::fs::read_dir("input/fixtures")
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "h"))
        .collect();
    entries.sort();

    let mut tests = String::from("// @generated by build.rs\n");
    for path in &entries {
        let stem = path.file_stem().unwrap().to_string_lossy();
        let ident = rust_ident(&stem);
        tests.push_str(&format!("#[test]\nfn {ident}() {{ run({stem:?}); }}\n"));
    }

    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("fixture_tests.rs");
    std::fs::write(out, tests).unwrap();
}
