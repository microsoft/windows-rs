/// Events that only forward to a Reactor callback subscribe when the first callback is set, or
/// when one of their `active_properties` is set. Events that observe properties or item order,
/// track selection, or report managed image state subscribe at creation because they do work
/// without a callback.
fn is_lazy_event(object: &Object, event: &Event) -> bool {
    !event.property_changed
        && event.observes.is_none()
        && event.reorders.is_none()
        && event.value != Value::ContentDialogResult
        && !object
            .selection
            .as_ref()
            .is_some_and(|selection| selection.event == event.name)
        && !object
            .properties
            .iter()
            .any(|property| property.adapter == Some(PropertyAdapter::ImageUri))
}

fn native_interface_value(
    target: &str,
    class: &str,
    interface: &str,
    metadata: &tool_reactor_metadata::MetadataResolver,
) -> String {
    if metadata.is_default_interface(class, interface) {
        target.to_string()
    } else {
        format!("{target}.cast::<native::{interface}>()?")
    }
}

fn native_interface_owned(
    target: &str,
    class: &str,
    interface: &str,
    metadata: &tool_reactor_metadata::MetadataResolver,
) -> String {
    if metadata.is_default_interface(class, interface) {
        format!("{target}.clone()")
    } else {
        format!("{target}.cast::<native::{interface}>()?")
    }
}

fn native_interface_call(
    target: &str,
    class: &str,
    interface: &str,
    metadata: &tool_reactor_metadata::MetadataResolver,
    call: impl FnOnce(&str) -> String,
) -> String {
    if metadata.is_default_interface(class, interface) {
        call(target)
    } else {
        let call = call("object");
        format!(
            "{target}.cast::<native::{interface}>().map_err(Into::into)\
             .and_then(|object| {call})"
        )
    }
}

struct DependencyProperty {
    kind: Option<String>,
    property: String,
    class: String,
    native: String,
    conversion: &'static str,
}

pub struct DependencyProperties {
    properties: Vec<DependencyProperty>,
    enums: BTreeMap<String, (String, Vec<String>)>,
}

// Properties set through `DependencyObject::SetValue`. The conversion tells the hand-written
// boxing code how to interpret a `PropertyValue` whose variant alone is ambiguous. Adapters
// returning `None` need native work beyond setting a dependency property.
fn dependency_conversion(adapter: Option<PropertyAdapter>) -> Option<&'static str> {
    Some(match adapter {
        None
        | Some(
            PropertyAdapter::DateTime
            | PropertyAdapter::ImageUri
            | PropertyAdapter::InspectableString
            | PropertyAdapter::InspectableStringList
            | PropertyAdapter::OptionalDateTime
            | PropertyAdapter::SelectionIndex
            | PropertyAdapter::ThemeBrush
            | PropertyAdapter::ThemeTransitions,
        ) => "Value",
        Some(PropertyAdapter::FontFamily) => "FontFamily",
        Some(PropertyAdapter::NativeColor) => "NativeColor",
        Some(PropertyAdapter::NumberBoxValue) => "NumberBox",
        Some(PropertyAdapter::PathData) => "PathData",
        Some(PropertyAdapter::RatingValue) => "Rating",
        Some(PropertyAdapter::Uri) => "Uri",
        _ => return None,
    })
}

// Attached and visual properties apply to every object and take precedence over an object's
// own property of the same name.
pub fn dependency_properties(
    schema: &Schema,
    metadata: &tool_reactor_metadata::MetadataResolver,
) -> DependencyProperties {
    let mut result = DependencyProperties {
        properties: Vec::new(),
        enums: BTreeMap::new(),
    };
    // Enum values are typed by the native setter, which is static for attached properties.
    let mut add = |kind: Option<&str>,
                   property: &str,
                   owner: &str,
                   native: &str,
                   value: &Value,
                   conversion: &'static str,
                   attached: bool| {
        let (class, _) = metadata
            .dependency_property(owner, native)
            .unwrap_or_else(|| panic!("cannot resolve {owner}.{native} dependency property"));
        if let Some(value) = value.enum_name() {
            let (path, variants) = if attached {
                let setter = format!("Set{native}");
                (
                    metadata.static_enum_path(owner, &setter),
                    metadata.static_enum_info(owner, &setter),
                )
            } else {
                let setter = format!("put_{native}");
                (
                    metadata.enum_path(owner, &setter),
                    metadata.enum_info(owner, &setter),
                )
            };
            let (Some(path), Some((_, variants))) = (path, variants) else {
                panic!("cannot resolve {owner}.{native} enum");
            };
            result
                .enums
                .entry(value.to_string())
                .or_insert_with(|| (path, variants.to_vec()));
        }
        result.properties.push(DependencyProperty {
            kind: kind.map(str::to_string),
            property: property.to_string(),
            class,
            native: native.to_string(),
            conversion,
        });
    };
    let mut shared = BTreeSet::new();
    for property in &schema.attached_properties {
        let owner = property.owner.rsplit('.').next().unwrap();
        add(
            None,
            &property.name,
            owner,
            &property.native,
            &property.value,
            "Value",
            true,
        );
        shared.insert(property.name.as_str());
    }
    if schema.objects.iter().any(|object| object.enabled) {
        add(
            None,
            "IsEnabled",
            "Control",
            "IsEnabled",
            &Value::Bool,
            "Value",
            false,
        );
        shared.insert("IsEnabled");
    }
    for property in &schema.visual_properties {
        let owner = property.owner.rsplit('.').next().unwrap();
        let conversion = dependency_conversion(property.adapter).unwrap();
        add(
            None,
            &property.name,
            owner,
            &property.name,
            &property.value,
            conversion,
            false,
        );
        shared.insert(property.name.as_str());
    }
    for object in schema
        .objects
        .iter()
        .filter(|object| !object.handwritten || object.category == ObjectCategory::Visual)
    {
        let owner = if object.handwritten {
            object.native_path().rsplit('.').next().unwrap().to_string()
        } else {
            native_name(object)
        };
        for property in &object.properties {
            if shared.contains(property.name.as_str())
                || object.handwritten
                    && (property.controlled.is_some() || property.coerces.is_some())
            {
                continue;
            }
            let Some(conversion) = dependency_conversion(property.adapter) else {
                continue;
            };
            let native = native_property(property);
            add(
                Some(&object.name),
                &property.name,
                &owner,
                native,
                &property.value,
                conversion,
                false,
            );
        }
    }
    result
}

fn emit_dependency_properties(output: &mut String, dependencies: &DependencyProperties) {
    output.push_str(
        "fn dependency_property(kind: ObjectType, property: PropertyId) -> \
         Option<(fn() -> windows_core::Result<native::DependencyProperty>, Conversion)> { \
         Some(match (kind, property) {\n",
    );
    for property in &dependencies.properties {
        let kind = property
            .kind
            .as_ref()
            .map_or_else(|| "_".to_string(), |kind| format!("ObjectType::{kind}"));
        let class = property.class.rsplit('.').next().unwrap();
        output.push_str(&format!(
            "({kind}, PropertyId::{}) => (native::{class}::{}Property, Conversion::{}),\n",
            property.property, property.native, property.conversion
        ));
    }
    output.push_str("_ => return None,\n}) }\n");
    output.push_str("fn box_enum(kind: &str, variant: &str) -> IInspectable { match kind {\n");
    for (kind, (_, variants)) in &dependencies.enums {
        let arms = variants
            .iter()
            .map(|variant| format!("\"{variant}\" => native::{kind}::{variant},"))
            .collect::<String>();
        output.push_str(&format!(
            "\"{kind}\" => windows_reference::IReference::from(match variant {{ {arms} \
             _ => unreachable!(\"validated enum variant\") }}).into(),\n"
        ));
    }
    output.push_str("_ => unreachable!(\"validated enum kind\"),\n} }\n");
}

pub fn dependency_filters(dependencies: &DependencyProperties) -> Vec<String> {
    dependencies
        .properties
        .iter()
        .map(|property| format!("{}::{}Property", property.class, property.native))
        .chain(dependencies.enums.values().map(|(path, _)| path.clone()))
        .collect()
}

fn emit_native_property_arms(
    output: &mut String,
    pattern: &str,
    target: &str,
    class: &str,
    native: &str,
    adapter: PropertyAdapter,
    metadata: &tool_reactor_metadata::MetadataResolver,
) {
    match adapter {
        PropertyAdapter::ImplicitTranslation => output.push_str(&format!(
            "{pattern}None) => Some({target}.cast::<native::UIElement>().map_err(Into::into)\
             .and_then(|object| object.SetTranslation(native::Vector3::default()).map_err(Into::into))),\n\
             {pattern}Some(PropertyValue::Vector2(value))) => \
             Some({target}.cast::<native::UIElement>().map_err(Into::into)\
             .and_then(|object| object.SetTranslation(native::Vector3 {{ \
             x: value[0] as f32, y: value[1] as f32, z: 0.0 }}).map_err(Into::into))),\n"
        )),
        PropertyAdapter::ImplicitScale => output.push_str(&format!(
            "{pattern}None) => Some({target}.cast::<native::UIElement>().map_err(Into::into)\
             .and_then(|object| set_implicit_scale(&object, 1.0))),\n\
             {pattern}Some(PropertyValue::F64(value))) => \
             Some({target}.cast::<native::UIElement>().map_err(Into::into)\
             .and_then(|object| set_implicit_scale(&object, *value))),\n"
        )),
        PropertyAdapter::ImplicitOpacityTransition
        | PropertyAdapter::ImplicitScaleTransition
        | PropertyAdapter::ImplicitTranslationTransition => {
            let helper = match adapter {
                PropertyAdapter::ImplicitOpacityTransition => "set_opacity_transition",
                PropertyAdapter::ImplicitTranslationTransition => "set_translation_transition",
                _ => "set_scale_transition",
            };
            output.push_str(&format!(
                "{pattern}None) => Some({target}.cast::<native::UIElement>().map_err(Into::into)\
                 .and_then(|object| {helper}(&object, None))),\n\
                 {pattern}Some(PropertyValue::Duration(value))) => \
                 Some({target}.cast::<native::UIElement>().map_err(Into::into)\
                 .and_then(|object| {helper}(&object, Some(*value)))),\n"
            ));
        }
        PropertyAdapter::EditText => output.push_str(&format!(
            "{pattern}None) => Some(set_edit_text(&{target}, \"\")),\n\
             {pattern}Some(PropertyValue::String(value))) => \
             Some(set_edit_text(&{target}, value)),\n"
        )),
        PropertyAdapter::RichEditText => output.push_str(&format!(
            "{pattern}None) => Some(set_rich_edit_text(&{target}, \"\")),\n\
             {pattern}Some(PropertyValue::String(value))) => \
             Some(set_rich_edit_text(&{target}, value)),\n"
        )),
        PropertyAdapter::RichTextBlocks => output.push_str(&format!(
            "{pattern}None) => Some(set_rich_text_blocks({target}, None)),\n\
             {pattern}Some(PropertyValue::RichText(value))) => \
             Some(set_rich_text_blocks({target}, Some(value))),\n"
        )),
        PropertyAdapter::IconElement | PropertyAdapter::IconSource => {
            let (icon_type, helper) = if adapter == PropertyAdapter::IconElement {
                ("IconElement", "icon_element")
            } else {
                ("IconSource", "icon_source")
            };
            let interface = metadata
                .resolve(class, &format!("put_{native}"))
                .unwrap()
                .short_name();
            let clear = native_interface_call(target, class, interface, metadata, |object| {
                format!("{object}.Set{native}(None::<&native::{icon_type}>).map_err(Into::into)")
            });
            let set = native_interface_call(target, class, interface, metadata, |object| {
                format!(
                    "{helper}(value, image).and_then(|icon| \
                     {object}.Set{native}(&icon).map_err(Into::into))"
                )
            });
            output.push_str(&format!(
                "{pattern}None) => Some({clear}),\n\
                 {pattern}Some(PropertyValue::Icon(value))) => Some({set}),\n"
            ));
        }
        PropertyAdapter::GridRows | PropertyAdapter::GridColumns => {
            let rows = adapter == PropertyAdapter::GridRows;
            output.push_str(&format!(
                "{pattern}None) => Some(set_grid_definitions({target}, &[], {rows})),\n\
                 {pattern}Some(PropertyValue::GridLengths(value))) => \
                 Some(set_grid_definitions({target}, value, {rows})),\n"
            ));
        }
        adapter => panic!("{class}.{native} has unsupported native adapter {adapter:?}"),
    }
}
