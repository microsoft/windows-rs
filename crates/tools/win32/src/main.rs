fn main() {
    let time = std::time::Instant::now();
    let args: Vec<_> = std::env::args().skip(1).collect();
    let (audio, rdl_only, headers) = match args.as_slice() {
        [] => (false, false, None),
        [arg] if arg == "--clang2-audio" => (true, false, None),
        [arg, mode] if arg == "--clang2-audio" && mode == "--rdl-only" => (true, true, None),
        [arg, headers, mode] if arg == "--clang2-headers" && mode == "--rdl-only" => {
            (false, true, Some(headers))
        }
        _ => panic!(
            "usage: tool-win32 [--clang2-audio [--rdl-only] | --clang2-headers header,...|all --rdl-only]"
        ),
    };

    for name in ARCHS {
        assert!(
            Arch::known(name).is_some(),
            "unknown architecture `{name}` in `ARCHS` (known: x64, arm64, x86)"
        );
    }

    // Validate the toolchain is the pinned, reproducible one before scraping a single header:
    // the loaded libclang must match `LIBCLANG_VERSION`, and the pinned SDK/WDK packages must be
    // restorable. This is what guarantees the committed metadata can be regenerated byte-for-byte
    // here and in CI. Everything is provisioned on demand (pinned libclang and the SDK/WDK NuGet
    // packages are fetched + cached on first use) so a fresh checkout "just works" without a
    // manual `nuget restore`. Shared by both scrape phases, so it runs once here.
    ensure_libclang();
    assert_libclang_version();

    if let Some(headers) = headers {
        if let Err(error) = clang2::headers(&headers.split(',').collect::<Vec<_>>()) {
            eprintln!("{error}");
            std::process::exit(1);
        }
        return;
    }

    if audio {
        if let Err(error) = clang2::audio(rdl_only) {
            eprintln!("{error}");
            std::process::exit(1);
        }
        return;
    }

    if let Some(headers) = std::env::var_os("WINDOWS_CLANG") {
        let rejected = if headers == "km" {
            km::scrape(&std::path::Path::new(OUTPUT_DIR).join("Windows.Win32.winmd"))
        } else {
            scrape_um(&headers.to_string_lossy())
        };
        if rejected != 0 {
            eprintln!(
                "clang2 coverage is incomplete: {rejected} rejected architecture-root entries; see production inventories"
            );
            std::process::exit(1);
        }
        return;
    }

    let um_rejected = scrape_um("all");
    let output = std::path::Path::new(OUTPUT_DIR);
    let km_rejected = km::scrape(&output.join("Windows.Win32.winmd"));
    replace_rdl(&output.join("rdl"), std::path::Path::new(RDL_DIR));
    replace_rdl(&output.join("km/rdl"), std::path::Path::new(km::RDL_DIR));
    std::fs::copy(output.join("Windows.Win32.merged.winmd"), MERGED_WINMD).unwrap();
    println!(
        "Wrote `{MERGED_WINMD}` in {:.2}s",
        time.elapsed().as_secs_f32()
    );
    if um_rejected + km_rejected != 0 {
        eprintln!(
            "Published incomplete clang2 candidate metadata: {um_rejected} SDK and {km_rejected} WDK rejected architecture-root entries; see production inventories"
        );
        std::process::exit(1);
    }
}

fn replace_rdl(source: &std::path::Path, destination: &std::path::Path) {
    let files: Vec<_> = std::fs::read_dir(source)
        .unwrap_or_else(|error| panic!("failed to read `{}`: {error}", source.display()))
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<_, _>>()
        .unwrap_or_else(|error| panic!("failed to enumerate `{}`: {error}", source.display()));
    let files: Vec<_> = files
        .into_iter()
        .filter(|path| path.extension().is_some_and(|extension| extension == "rdl"))
        .collect();
    assert!(
        !files.is_empty(),
        "generated RDL directory `{}` is empty",
        source.display()
    );

    let parent = destination.parent().unwrap();
    let name = destination.file_name().unwrap().to_string_lossy();
    let staging = parent.join(format!(".{name}.staging"));
    let backup = parent.join(format!(".{name}.backup"));
    if !destination.exists() && backup.exists() {
        std::fs::rename(&backup, destination).unwrap_or_else(|error| {
            panic!(
                "failed to restore `{}` from `{}`: {error}",
                destination.display(),
                backup.display()
            )
        });
    }
    if staging.exists() {
        std::fs::remove_dir_all(&staging).unwrap();
    }
    if backup.exists() {
        std::fs::remove_dir_all(&backup).unwrap();
    }
    std::fs::create_dir_all(&staging).unwrap();
    if destination.exists() {
        for entry in std::fs::read_dir(destination)
            .unwrap_or_else(|error| panic!("failed to read `{}`: {error}", destination.display()))
        {
            let path = entry
                .unwrap_or_else(|error| {
                    panic!("failed to enumerate `{}`: {error}", destination.display())
                })
                .path();
            if path.is_file() && path.extension().is_none_or(|extension| extension != "rdl") {
                std::fs::copy(&path, staging.join(path.file_name().unwrap())).unwrap_or_else(
                    |error| {
                        panic!(
                            "failed to preserve non-RDL file `{}`: {error}",
                            path.display()
                        )
                    },
                );
            }
        }
    }
    for path in &files {
        std::fs::copy(path, staging.join(path.file_name().unwrap())).unwrap_or_else(|error| {
            panic!(
                "failed to stage generated RDL `{}`: {error}",
                path.display()
            )
        });
    }

    if destination.exists() {
        std::fs::rename(destination, &backup).unwrap_or_else(|error| {
            panic!(
                "failed to preserve `{}` before replacement: {error}",
                destination.display()
            )
        });
    }
    if let Err(error) = std::fs::rename(&staging, destination) {
        if backup.exists() {
            std::fs::rename(&backup, destination).unwrap_or_else(|restore_error| {
                panic!(
                    "failed to install `{}` ({error}) and failed to restore it ({restore_error})",
                    destination.display()
                )
            });
        }
        panic!("failed to install `{}`: {error}", destination.display());
    }
    if backup.exists() {
        std::fs::remove_dir_all(&backup).unwrap();
    }
}

fn scrape_um(headers: &str) -> usize {
    assert_no_duplicate_headers();
    let full = headers.trim() == "all";
    let headers: Vec<_> = if full {
        HEADERS.iter().chain(SATELLITE_HEADERS).copied().collect()
    } else if let Some(count) = headers.trim().strip_prefix("first:") {
        let count: usize = count.parse().expect("invalid WINDOWS_CLANG header count");
        HEADERS[..count.min(HEADERS.len())].to_vec()
    } else {
        headers
            .split(',')
            .map(str::trim)
            .filter(|header| !header.is_empty())
            .collect()
    };
    assert!(
        !headers.is_empty(),
        "WINDOWS_CLANG must name at least one comma-separated header"
    );

    let include_dirs = sdk_include_dirs();
    let inputs = clang_inputs(&headers, &include_dirs, full);
    let include_args: Vec<String> = include_dirs
        .iter()
        .cloned()
        .flat_map(|dir| ["-isystem".to_string(), dir])
        .collect();
    let archs = canonical_archs();
    let resource_dir = (archs.len() > 1).then(clang_resource_dir);
    let output_dir = std::path::Path::new(OUTPUT_DIR);
    clang2::clear_outputs(output_dir).unwrap();
    let references = windows_metadata::reader::Index::new(vec![
        windows_metadata::reader::File::new(windows_default::WINRT.to_vec()).unwrap(),
    ]);

    let outputs: Vec<_> = archs
        .iter()
        .map(|arch| {
            scrape_um_arch(
                arch,
                inputs.clone(),
                &include_args,
                &references,
                resource_dir.as_deref(),
                output_dir,
            )
        })
        .collect();

    let final_rdl = output_dir.join("rdl");
    let arch_inputs: Vec<windows_rdl::ArchInput> = outputs
        .iter()
        .map(|output| windows_rdl::ArchInput {
            rdl_dir: output.rdl_dir.clone(),
            winmd: output.winmd.clone(),
            bits: output.bits,
        })
        .collect();
    let merge_time = std::time::Instant::now();
    windows_rdl::merge_arch_rdl(
        &arch_inputs,
        Some(std::path::Path::new(METADATA_SEED)),
        &final_rdl,
    )
    .unwrap();
    println!(
        "Arch-merged {} in {:.2}s",
        outputs
            .iter()
            .map(|output| output.name.as_str())
            .collect::<Vec<_>>()
            .join(" + "),
        merge_time.elapsed().as_secs_f32()
    );

    let final_winmd = output_dir.join("Windows.Win32.winmd");
    let metadata_time = std::time::Instant::now();
    windows_rdl::reader()
        .input(METADATA_SEED)
        .input("crates/libs/clang2/metadata.rdl")
        .input(&final_rdl)
        .reference_bytes(windows_default::WINRT)
        .output(&final_winmd)
        .write()
        .unwrap();
    println!(
        "Compiled merged winmd in {:.2}s",
        metadata_time.elapsed().as_secs_f32()
    );

    let canonical = &outputs[0];
    println!(
        "Wrote {} from {} input header(s), {} merged RDL partition(s), {} x64 exported function(s), {} x64 unsupported root declaration(s)",
        final_winmd.display(),
        headers.len(),
        std::fs::read_dir(&final_rdl).unwrap().flatten().count(),
        canonical.functions,
        canonical.unsupported.len()
    );
    outputs.iter().map(|output| output.unsupported.len()).sum()
}

fn clang_inputs(headers: &[&str], include_dirs: &[String], full: bool) -> Vec<HeaderInput> {
    clang_inputs_with_prerequisites(headers, include_dirs, full, |_| &[], false)
}

// Inputs are in canonical precedence order: grouped main declarations before satellite variants.
fn clang_inputs_with_prerequisites(
    headers: &[&str],
    include_dirs: &[String],
    full: bool,
    prerequisites: impl Fn(&str) -> &'static [&'static str],
    define_guids: bool,
) -> Vec<HeaderInput> {
    let (satellite_headers, main_headers): (Vec<_>, Vec<_>) = headers
        .iter()
        .copied()
        .partition(|header| SATELLITE_HEADERS.contains(header));
    let mut inputs = Vec::new();
    let prelude = if define_guids {
        // Definitions after the base pass avoid duplicate unguarded storage GUIDs.
        format!("{PRELUDE}\n#include <initguid.h>")
    } else {
        PRELUDE.to_string()
    };
    if !main_headers.is_empty() {
        let roots = main_headers
            .iter()
            .map(|header| resolve(header, include_dirs, "header", "pinned SDK include"));
        let mut source = prelude.clone();
        // Some main headers reach devicetopology.h before the manifest's ks.h entry. Load KS
        // first so devicetopology.h does not declare its layout-compatible fallback types.
        if satellite_headers.contains(&"devicetopology.h") {
            source.push_str("\n#include <ks.h>");
        }
        for header in &main_headers {
            for prerequisite in prerequisites(header) {
                source.push_str(&format!("\n#include <{prerequisite}>"));
            }
            source.push_str(&format!("\n#include <{header}>"));
        }
        let mut input = HeaderInput {
            name: "clang-win32-main.hpp".into(),
            source,
            roots: roots.collect(),
            root_dirs: vec![],
            excluded_roots: vec![],
        };
        if full {
            input.root_dirs = scope_dirs(include_dirs, SCOPE);
            input.excluded_roots = EXCLUDE_HEADERS
                .iter()
                .filter_map(|header| find_in_dirs(header, include_dirs))
                .collect();
        }
        inputs.push(input);
    }
    if !satellite_headers.is_empty() {
        let roots = satellite_headers
            .iter()
            .map(|header| resolve(header, include_dirs, "header", "pinned SDK include"));
        let mut source = prelude;
        if !define_guids {
            source.push_str(GUID_RESET);
        }
        for header in &satellite_headers {
            // Its internal ks.h include requests only IKsControl and otherwise declares fallback
            // KS types. Load the full KS surface first so those duplicate fallbacks stay disabled.
            if *header == "devicetopology.h" {
                source.push_str("\n#include <ks.h>\n#define _KS_");
            }
            for prerequisite in prerequisites(header) {
                source.push_str(&format!("\n#include <{prerequisite}>"));
            }
            source.push_str(&format!("\n#include <{header}>"));
            if !define_guids {
                source.push_str(GUID_RESET);
            }
        }
        inputs.push(HeaderInput {
            name: "clang-win32-satellite.hpp".into(),
            source,
            roots: roots.collect(),
            root_dirs: vec![],
            excluded_roots: vec![],
        });
    }
    inputs
}

#[derive(Clone)]
struct HeaderInput {
    name: String,
    source: String,
    roots: Vec<String>,
    root_dirs: Vec<String>,
    excluded_roots: Vec<String>,
}

fn scope_dirs(include_dirs: &[String], scopes: &[&str]) -> Vec<String> {
    include_dirs
        .iter()
        .filter(|dir| {
            std::path::Path::new(dir)
                .file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| scopes.contains(&name))
        })
        .cloned()
        .collect()
}

struct ArchOutput {
    name: String,
    bits: i32,
    rdl_dir: std::path::PathBuf,
    winmd: std::path::PathBuf,
    functions: usize,
    unsupported: Vec<String>,
}

fn clang_arguments(
    arch: &Arch,
    include_args: &[String],
    resource_dir: Option<&str>,
    sal_shim: &str,
) -> Vec<String> {
    let mut owned_args: Vec<String> = CLANG_ARGS.iter().map(|arg| arg.to_string()).collect();
    owned_args.extend([
        format!("--target={}", arch.triple),
        "-fms-extensions".to_string(),
        "-include".to_string(),
        sal_shim.to_string(),
    ]);
    if arch.name != "x64"
        && let Some(resource_dir) = resource_dir
    {
        owned_args.extend(["-resource-dir".to_string(), resource_dir.to_string()]);
    }
    owned_args.extend(arch.defines.iter().cloned());
    owned_args.extend(include_args.iter().cloned());
    owned_args
}

fn scrape_um_arch(
    arch: &Arch,
    inputs: Vec<HeaderInput>,
    include_args: &[String],
    references: &windows_metadata::reader::Index,
    resource_dir: Option<&str>,
    output_dir: &std::path::Path,
) -> ArchOutput {
    let owned_args = clang_arguments(arch, include_args, resource_dir, SAL_SHIM);
    let args: Vec<&str> = owned_args.iter().map(String::as_str).collect();
    let arch_dir = output_dir.join(&arch.name);
    let lib_dirs = sdk_lib_dirs_for_arch(&arch.name);
    let libraries: Vec<_> = IMPORT_LIBS
        .iter()
        .copied()
        .chain(["windows.ui.lib"])
        .collect();
    let import_libs = clang2::production_libraries(&libraries, &lib_dirs, &arch_dir).unwrap();
    let (options, excluded) =
        clang2::production_options(&import_libs, references, &arch_dir).unwrap();
    let result = clang2::scrape(inputs, &args, &options, &excluded, &arch_dir).unwrap();
    let rdl_dir = arch_dir.join("rdl");
    let winmd = arch_dir.join("Windows.Win32.winmd");
    let metadata_time = std::time::Instant::now();
    windows_rdl::reader()
        .input(METADATA_SEED)
        .input("crates/libs/clang2/metadata.rdl")
        .input(&rdl_dir)
        .reference_bytes(windows_default::WINRT)
        .output(&winmd)
        .write()
        .unwrap();
    println!(
        "Compiled {} winmd in {:.2}s",
        arch.name,
        metadata_time.elapsed().as_secs_f32()
    );
    ArchOutput {
        name: arch.name.clone(),
        bits: arch.bits,
        rdl_dir,
        winmd,
        functions: result.functions,
        unsupported: result.unsupported,
    }
}

/// x64 is always canonical (its scrape writes the committed metadata); any other arch listed in
/// [`ARCHS`] is folded in via arch-merge. Every arch name in `ARCHS` is validated in `main`.
fn canonical_archs() -> Vec<Arch> {
    let extra: Vec<String> = ARCHS.iter().map(|name| name.to_string()).collect();
    Arch::canonical_plus(&extra, |name| Arch::known(name).unwrap())
}

/// Panics if any header name appears more than once across [`HEADERS`] and [`SATELLITE_HEADERS`].
/// Duplicates are silently absorbed by clang's USR dedup, so a stray copy would otherwise go
/// unnoticed; failing fast keeps the header lists honest.
fn assert_no_duplicate_headers() {
    let mut seen = std::collections::BTreeSet::new();
    for header in HEADERS.iter().chain(SATELLITE_HEADERS) {
        assert!(
            seen.insert(*header),
            "duplicate header `{header}` (listed more than once across `HEADERS` / `SATELLITE_HEADERS`)"
        );
    }
}

fn rdl_partition_stem(header: &str) -> String {
    std::path::Path::new(header)
        .file_stem()
        .unwrap()
        .to_string_lossy()
        .chars()
        .filter(|ch| *ch != '.')
        .flat_map(char::to_lowercase)
        .collect()
}

/// The pinned SDK include directories, in a fixed order so the parse is deterministic.
fn sdk_include_dirs() -> Vec<String> {
    let base = nuget_package("microsoft.windows.sdk.cpp", SDK_VERSION)
        .join("c")
        .join("Include")
        .join(marketing_dir(SDK_VERSION));
    ["ucrt", "um", "shared", "winrt", "cppwinrt"]
        .iter()
        .map(|seg| base.join(seg).to_string_lossy().replace('\\', "/"))
        .collect()
}

/// The pinned SDK x64 import-library directories for the bounded x64 header route.
fn sdk_lib_dirs() -> Vec<String> {
    sdk_lib_dirs_for_arch("x64")
}

fn sdk_lib_dirs_for_arch(arch: &str) -> Vec<String> {
    let base = nuget_package(&format!("microsoft.windows.sdk.cpp.{arch}"), SDK_VERSION).join("c");
    ["um", "ucrt"]
        .iter()
        .map(|seg| {
            base.join(seg)
                .join(arch)
                .to_string_lossy()
                .replace('\\', "/")
        })
        .collect()
}

fn resolve(name: &str, dirs: &[String], kind: &str, var: &str) -> String {
    find_in_dirs(name, dirs)
        .unwrap_or_else(|| panic!("{kind} `{name}` not found in any `{var}` directory"))
}

