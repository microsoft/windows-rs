//! Phase B: the additive kernel-mode WDK scrape.
//!
//! This is the *additive* companion to the user-mode Win32 scrape in `main.rs`: it parses the
//! kernel-mode WDK headers and emits only the surface the WDK adds on top of Win32, into the same
//! flat `Windows.Win32` namespace. Every entity Win32 already defines is skipped (see
//! [`REFERENCE_WINMD`]) and resolved by bare name once both winmds are loaded together. Like the um
//! scrape contains no type-level curation - the only inputs are mechanical.
//!
//! The two phases share one crate: the pinned SDK version, root namespace, SAL shim, and arch list
//! all live in `main.rs` and are referenced here as `crate::*`, and the toolchain is provisioned
//! once by the orchestrator. This phase resolves against phase A's generated WinMD directly
//! (phase A wrote it from the same inputs an isolated re-derivation would use), so no intermediate
//! re-compile of the committed RDL is needed.

use helpers::*;
use std::path::PathBuf;

/// Where the WDK RDL snapshot is written (committed, human-reviewable), one file per defining
/// header (`wdm.rdl`, `ntifs.rdl`, ...) exactly like `metadata/win32`. Regenerated by running the
/// tool; treat it as generated output, not a place to hand-edit.
pub(super) const RDL_DIR: &str = "metadata/wdk";

/// Pinned WDK version. The metadata is generated against the `Microsoft.Windows.WDK.x64` NuGet
/// package at this exact version, restored into the NuGet global cache. This is the latest
/// servicing build of the `10.0.28000` marketing line that matches the SDK; the WDK's servicing
/// build lags the SDK's, so it is pinned independently from `crate::SDK_VERSION`.
const WDK_VERSION: &str = "10.0.28000.1839";

/// Arch-neutral clang arguments shared by every architecture pass. Parse as C++ (for `extern "C"`,
/// `__declspec`, SAL). The per-arch target triple and the arch-selection macros are supplied
/// separately (see [`arch_defines`]); the kernel-mode headers never pull `windows.h`, so `ntdef.h`
/// errors "No Target Architecture" without those macros the SDK build normally sets.
/// `NTDDI_VERSION` gates the API level.
const CLANG_ARGS: &[&str] = &[
    "-x",
    "c++",
    "-std=c++20",
    "-ferror-limit=0",
    "-DNTDDI_VERSION=0x0A000010",
];

/// In-scope header directory segments (`["km"]`): a declaration defined under the WDK kernel-mode
/// include folder is emitted unconditionally; the SDK `um`/`shared`/`ucrt` closure the translation
/// unit pulls in to compile is emitted only when a `km` declaration references it (and then dropped
/// anyway if Win32 already defines it), so the CRT/toolset noise never reaches the metadata.
const SCOPE: &[&str] = &["km"];

/// The WDK source headers. `ntifs.h` comes *before* `wdm.h`: it defines
/// `_NTIFS_INCLUDED_` and the `PEPROCESS`/`PETHREAD` opaque typedefs first, so including it second
/// would collide with `wdm.h`'s own forward declarations of the same names. `offreg.h` is a
/// user-mode API without prerequisite includes; its separate profile uses the SDK Windows
/// prelude instead of supplying synthetic typedefs.
const SOURCE_HEADERS: &[&str] = &["ntifs.h", "wdm.h", "offreg.h"];

/// Import libraries (bare names, resolved against the SDK and WDK x64 lib trees) read to recover
/// the function -> DLL mapping the headers do not carry: `ntdll.lib` (`NtReadFile`,
/// `RtlGetVersion`, ...) from the SDK and `offreg.lib` (`ORCreateHive`, ...) from the WDK.
/// Unrouted routines, including kernel-only `ntoskrnl` exports, are reported as rejected roots.
const IMPORT_LIBS: &[&str] = &["ntdll.lib", "offreg.lib"];

/// The known arch plus the preprocessor defines the kernel-mode headers need for this target.
fn arch(name: &str) -> Arch {
    let mut arch = Arch::known(name).unwrap();
    arch.defines = arch_defines(name);
    arch
}

/// The arch-selection preprocessor macros the kernel headers require in place of the `windows.h`
/// closure that would otherwise define them.
fn arch_defines(name: &str) -> Vec<String> {
    let defines: &[&str] = match name {
        "x64" => &["-D_AMD64_", "-DAMD64", "-D_WIN64"],
        "arm64" => &["-D_ARM64_", "-DARM64", "-D_WIN64"],
        "x86" => &["-D_X86_", "-Di386=1"],
        _ => &[],
    };
    defines.iter().map(|s| s.to_string()).collect()
}

/// The `-isystem` include arguments: the WDK kernel-mode headers first (`km`, then the WDK's own
/// `shared`), then the shared Windows SDK headers (`shared`, `um`, `ucrt`) that complete the
/// translation unit. Order is fixed so the parse is deterministic.
fn include_args() -> Vec<String> {
    let sdk_version = crate::SDK_VERSION;
    let wdk = nuget_package("microsoft.windows.wdk.x64", WDK_VERSION)
        .join("c")
        .join("Include")
        .join(marketing_dir(WDK_VERSION));
    let sdk = nuget_package("microsoft.windows.sdk.cpp", sdk_version)
        .join("c")
        .join("Include")
        .join(marketing_dir(sdk_version));
    let dirs = [
        wdk.join("km"),
        wdk.join("shared"),
        sdk.join("shared"),
        sdk.join("um"),
        sdk.join("ucrt"),
    ];
    dirs.iter()
        .flat_map(|dir| {
            [
                "-isystem".to_string(),
                dir.to_string_lossy().replace('\\', "/"),
            ]
        })
        .collect()
}

/// Target-specific import-library directories: the SDK's `um` tree (`ntdll.lib`) and the WDK's
/// kernel-mode tree (`offreg.lib`). Native linker spellings come from this target's archives.
fn lib_dirs(arch: &str) -> Vec<String> {
    let sdk = nuget_package(
        &format!("microsoft.windows.sdk.cpp.{arch}"),
        crate::SDK_VERSION,
    )
    .join("c")
    .join("um")
    .join(arch);
    let wdk = nuget_package(&format!("microsoft.windows.wdk.{arch}"), WDK_VERSION)
        .join("c")
        .join("Lib")
        .join(marketing_dir(WDK_VERSION))
        .join("km")
        .join(arch);
    [sdk, wdk]
        .iter()
        .map(|dir: &PathBuf| dir.to_string_lossy().replace('\\', "/"))
        .collect()
}

struct ArchOutput {
    bits: i32,
    rdl_dir: PathBuf,
    winmd: PathBuf,
    functions: usize,
    unsupported: Vec<String>,
}

pub fn scrape(um_winmd: &std::path::Path) -> usize {
    assert!(
        um_winmd.is_file(),
        "kernel scrape requires `{}` from a prior full user-mode scrape",
        um_winmd.display()
    );
    let include_args = include_args();
    let include_dirs: Vec<_> = include_args
        .as_chunks::<2>()
        .0
        .iter()
        .map(|pair| pair[1].clone())
        .collect();
    let roots = SOURCE_HEADERS
        .iter()
        .map(|header| {
            find_in_dirs(header, &include_dirs)
                .unwrap_or_else(|| panic!("WDK header `{header}` was not found"))
        })
        .collect::<Vec<_>>();
    let source: String = SOURCE_HEADERS[..2]
        .iter()
        .map(|header| format!("#include <{header}>\n"))
        .collect();
    // Canonical kernel contracts take precedence over declarations in the SDK/offreg prelude.
    let inputs = vec![
        crate::HeaderInput {
            name: "clang-wdk.hpp".into(),
            source,
            roots: roots[..2].to_vec(),
            root_dirs: crate::scope_dirs(&include_dirs, SCOPE),
            excluded_roots: vec![],
        },
        crate::HeaderInput {
            name: "clang-wdk-offreg.hpp".into(),
            source: format!("{}\n#include <offreg.h>\n", crate::PRELUDE),
            roots: roots[2..].to_vec(),
            root_dirs: vec![],
            excluded_roots: vec![],
        },
    ];
    let um_bytes = std::fs::read(um_winmd).unwrap();
    let references = windows_metadata::reader::Index::new(vec![
        windows_metadata::reader::File::new(um_bytes).unwrap(),
        windows_metadata::reader::File::new(windows_default::WINRT.to_vec()).unwrap(),
    ]);

    let extra: Vec<String> = crate::ARCHS.iter().map(|name| name.to_string()).collect();
    let archs = Arch::canonical_plus(&extra, arch);
    let resource_dir = (archs.len() > 1).then(clang_resource_dir);
    let output_dir = std::path::Path::new(crate::OUTPUT_DIR).join("km");
    std::fs::create_dir_all(&output_dir).unwrap();
    let outputs: Vec<_> = archs
        .iter()
        .map(|arch| {
            scrape_arch(
                arch,
                inputs.clone(),
                &include_args,
                &references,
                resource_dir.as_deref(),
                &output_dir,
                um_winmd,
            )
        })
        .collect();

    let final_rdl = output_dir.join("rdl");
    let arch_inputs: Vec<windows_rdl::ArchInput> = outputs
        .iter()
        .map(|output| windows_rdl::ArchInput {
            rdl_dir: output.rdl_dir.clone(),
            winmd: output.winmd.clone(),
            bits: output.bits,
        })
        .collect();
    windows_rdl::merge_arch_rdl(&arch_inputs, None, &final_rdl).unwrap();
    let km_winmd = output_dir.join("Windows.Win32.km.winmd");
    windows_rdl::reader()
        .input(&final_rdl)
        .reference(um_winmd)
        .reference_bytes(windows_default::WINRT)
        .output(&km_winmd)
        .write()
        .unwrap();

    let merged = output_dir
        .parent()
        .unwrap()
        .join("Windows.Win32.merged.winmd");
    windows_metadata::merge()
        .input(um_winmd)
        .input(&km_winmd)
        .union_enums()
        .assembly_name("Windows.Win32")
        .output(&merged)
        .merge()
        .unwrap();
    let canonical = &outputs[0];
    println!(
        "Wrote {} from {} WDK header(s), {} RDL partition(s), {} x64 exported function(s), {} x64 unsupported root declaration(s)",
        merged.display(),
        SOURCE_HEADERS.len(),
        std::fs::read_dir(&final_rdl).unwrap().flatten().count(),
        canonical.functions,
        canonical.unsupported.len()
    );
    outputs.iter().map(|output| output.unsupported.len()).sum()
}

#[allow(clippy::too_many_arguments)]
fn scrape_arch(
    arch: &Arch,
    inputs: Vec<crate::HeaderInput>,
    include_args: &[String],
    references: &windows_metadata::reader::Index,
    resource_dir: Option<&str>,
    output_dir: &std::path::Path,
    um_winmd: &std::path::Path,
) -> ArchOutput {
    let mut owned_args: Vec<String> = CLANG_ARGS.iter().map(|arg| arg.to_string()).collect();
    owned_args.extend([
        format!("--target={}", arch.triple),
        "-fms-extensions".to_string(),
        "-include".to_string(),
        crate::SAL_SHIM.to_string(),
    ]);
    if arch.name != "x64"
        && let Some(resource_dir) = resource_dir
    {
        owned_args.extend(["-resource-dir".to_string(), resource_dir.to_string()]);
    }
    owned_args.extend(arch.defines.iter().cloned());
    owned_args.extend(include_args.iter().cloned());
    let args: Vec<&str> = owned_args.iter().map(String::as_str).collect();

    let arch_dir = output_dir.join(&arch.name);
    let import_libs =
        crate::clang2::production_libraries(IMPORT_LIBS, &lib_dirs(&arch.name), &arch_dir).unwrap();
    let (options, excluded) =
        crate::clang2::production_options(&import_libs, references, &arch_dir).unwrap();
    let result = crate::clang2::scrape(inputs, &args, &options, &excluded, &arch_dir).unwrap();
    let rdl_dir = arch_dir.join("rdl");
    let winmd = arch_dir.join("Windows.Win32.km.winmd");
    windows_rdl::reader()
        .input(&rdl_dir)
        .reference(um_winmd)
        .reference_bytes(windows_default::WINRT)
        .output(&winmd)
        .write()
        .unwrap();

    ArchOutput {
        bits: arch.bits,
        rdl_dir,
        winmd,
        functions: result.functions,
        unsupported: result.unsupported,
    }
}
