use super::*;
use roxmltree::{Document, Node};
use std::collections::{BTreeMap, BTreeSet};
use std::process::Command;

const SETUP: &str = "crates/libs/reactor-setup/assets";
type Classes = BTreeMap<String, BTreeMap<String, String>>;

pub fn generate(nuspec: &str, runtime: &Path, header: &str) {
    let family = define_literal(
        header,
        "WINDOWSAPPSDK_RUNTIME_PACKAGE_FRAMEWORK_PACKAGEFAMILYNAME",
    );
    let family = family
        .strip_prefix('"')
        .and_then(|s| s.strip_suffix('"'))
        .unwrap();
    let (name, _) = family.split_once('_').unwrap();
    let mut classes = Classes::new();
    for component in ["Foundation", "InteractiveExperiences", "WinUI"] {
        let id = format!("Microsoft.WindowsAppSDK.{component}");
        let version = nuspec_dependency_version(nuspec, &id);
        let fragment = nuget_package(&id, &version).join("runtimes-framework/package.appxfragment");
        let text = fs::read_to_string(&fragment).unwrap();
        read_classes(&text, &mut classes);
    }

    let mut shared_manifest = None;
    for arch in ["x64", "arm64", "x86"] {
        let msix = runtime.join(format!("tools/MSIX/win10-{arch}/{name}.msix"));
        let entries = tar(&msix, "-tf", None);
        let entries: BTreeSet<_> = entries
            .lines()
            .map(|line| line.split('/').next().unwrap().to_ascii_lowercase())
            .collect();
        let files: BTreeSet<_> = runtime::files(arch).collect();
        for file in &files {
            assert!(
                entries.contains(*file),
                "`{}` is missing `{file}`",
                msix.display()
            );
        }
        let text = tar(&msix, "-xOf", Some("AppxManifest.xml"));
        let doc = Document::parse(&text).unwrap();
        let identity = doc
            .descendants()
            .find(|n| n.has_tag_name("Identity"))
            .unwrap();
        assert_eq!(attribute(identity, "Name"), name);
        assert_eq!(attribute(identity, "ProcessorArchitecture"), arch);
        let manifest = manifest(&classes, &doc, &files);
        if arch == "x86" {
            write_asset("app-x86.manifest", &manifest);
        } else if let Some(shared) = &shared_manifest {
            assert_eq!(shared, &manifest, "x64 and arm64 activation entries differ");
        } else {
            shared_manifest = Some(manifest);
        }
    }
    write_asset("app.manifest", &shared_manifest.unwrap());
    write_asset("runtime-package.txt", name);
    let source = format!(
        "// Generated by tool-reactor-metadata. Do not edit.\n\
         const FRAMEWORK_FAMILY: PCWSTR = w!({family:?});\n\
         const FRAMEWORK_NAME: &str = {name:?};\n"
    );
    fs::write(
        workspace_path("crates/libs/reactor/src/native/runtime.rs"),
        source,
    )
    .unwrap();
}

fn write_asset(name: &str, text: &str) {
    fs::write(workspace_path(SETUP).join(name), text).unwrap();
}

fn tar(path: &Path, operation: &str, entry: Option<&str>) -> String {
    let exe = PathBuf::from(std::env::var_os("SystemRoot").unwrap()).join("System32/tar.exe");
    let output = Command::new(exe)
        .arg(operation)
        .arg(path)
        .args(entry)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "tar {operation} `{}` failed: {}",
        path.display(),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).unwrap()
}

fn attribute<'a>(node: Node<'a, '_>, name: &str) -> &'a str {
    node.attribute(name)
        .unwrap_or_else(|| panic!("missing `{name}` on {}", node.tag_name().name()))
}

fn child_text<'a>(node: Node<'a, '_>, name: &str) -> &'a str {
    node.children()
        .find(|n| n.has_tag_name(name))
        .and_then(|n| n.text())
        .unwrap_or_else(|| panic!("missing `{name}` on {}", node.tag_name().name()))
}

fn read_classes(text: &str, classes: &mut Classes) {
    let doc = Document::parse(text).unwrap();
    let mut count = 0;
    for server in doc
        .descendants()
        .filter(|n| n.has_tag_name("InProcessServer"))
    {
        let dll = child_text(server, "Path");
        let entries = classes.entry(dll.to_string()).or_default();
        for class in server
            .children()
            .filter(|n| n.is_element() && !n.has_tag_name("Path"))
        {
            assert!(
                class.has_tag_name("ActivatableClass"),
                "unsupported in-process registration"
            );
            let name = attribute(class, "ActivatableClassId");
            let model = attribute(class, "ThreadingModel");
            count += 1;
            if let Some(old) = entries.insert(name.to_string(), model.to_string()) {
                assert_eq!(old, model, "conflicting activation entry for `{name}`");
            }
        }
    }
    assert!(count > 0, "fragment contains no WinRT activation classes");
}

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn manifest(classes: &Classes, doc: &Document<'_>, files: &BTreeSet<&str>) -> String {
    let mut result = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n\
         <!-- Generated by tool-reactor-metadata from App SDK fragments and runtime MSIX metadata. -->\n\
         <assembly manifestVersion=\"1.0\"\n\
             xmlns=\"urn:schemas-microsoft-com:asm.v1\"\n\
             xmlns:winrtv1=\"urn:schemas-microsoft-com:winrt.v1\"\n\
             xmlns:asmv3=\"urn:schemas-microsoft-com:asm.v3\">\n",
    );
    for proxy in doc.descendants().filter(|n| n.has_tag_name("ProxyStub")) {
        let dll = child_text(proxy, "Path");
        if !files.contains(dll.to_ascii_lowercase().as_str()) {
            continue;
        }
        writeln!(result, "    <asmv3:file name=\"{}\">", xml(dll)).unwrap();
        writeln!(
            result,
            "        <asmv3:comClass clsid=\"{{{}}}\" />",
            xml(attribute(proxy, "ClassId"))
        )
        .unwrap();
        for interface in proxy
            .children()
            .filter(|n| n.is_element() && !n.has_tag_name("Path"))
        {
            assert!(
                interface.has_tag_name("Interface"),
                "unsupported proxy registration"
            );
            writeln!(
                result,
                "        <asmv3:comInterfaceProxyStub name=\"{}\" iid=\"{{{}}}\" />",
                xml(attribute(interface, "Name")),
                xml(attribute(interface, "InterfaceId"))
            )
            .unwrap();
        }
        result.push_str("    </asmv3:file>\n");
    }
    let mut registered = BTreeSet::new();
    for (dll, entries) in classes {
        assert!(
            files.contains(dll.to_ascii_lowercase().as_str())
                || dll.eq_ignore_ascii_case("Microsoft.Web.WebView2.Core.dll"),
            "activation DLL `{dll}` is not staged"
        );
        writeln!(result, "    <asmv3:file name=\"{}\">", xml(dll)).unwrap();
        for (name, model) in entries {
            assert!(
                registered.insert(name),
                "duplicate activation class `{name}`"
            );
            writeln!(
                result,
                "        <winrtv1:activatableClass name=\"{}\" threadingModel=\"{}\" />",
                xml(name),
                xml(model)
            )
            .unwrap();
        }
        result.push_str("    </asmv3:file>\n");
    }
    result.push_str("</assembly>\n");
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fragments_without_activation_classes_are_rejected() {
        let mut classes = Classes::new();
        read_classes(
            r#"<Fragment><InProcessServer><Path>Example.dll</Path>
            <ActivatableClass ActivatableClassId="Example.A" ThreadingModel="both"/>
            </InProcessServer></Fragment>"#,
            &mut classes,
        );
        for text in [
            "<Fragment/>",
            "<Fragment><UnknownServer/></Fragment>",
            "<Fragment><InProcessServer><Path>Example.dll</Path></InProcessServer></Fragment>",
        ] {
            assert!(std::panic::catch_unwind(|| read_classes(text, &mut classes.clone())).is_err());
        }
    }

    #[test]
    fn generates_selected_proxies_and_escaped_classes() {
        let mut classes = Classes::new();
        read_classes(
            r#"<Fragment><InProcessServer><Path>Example.dll</Path>
            <ActivatableClass ActivatableClassId="Example.A&amp;B" ThreadingModel="both"/>
            </InProcessServer></Fragment>"#,
            &mut classes,
        );
        let doc = Document::parse(
            r#"<Package><ProxyStub ClassId="01234567-1234-1234-1234-012345678901">
            <Path>Proxy.dll</Path><Interface Name="Example" InterfaceId="11234567-1234-1234-1234-012345678901"/>
            </ProxyStub></Package>"#,
        ).unwrap();
        for selected in [false, true] {
            let mut files = BTreeSet::from(["example.dll"]);
            if selected {
                files.insert("proxy.dll");
            }
            let output = manifest(&classes, &doc, &files);
            let output = Document::parse(&output).unwrap();
            let class = output
                .descendants()
                .find(|node| node.has_tag_name("activatableClass"))
                .unwrap();
            assert_eq!(class.attribute("name"), Some("Example.A&B"));
            assert_eq!(class.attribute("threadingModel"), Some("both"));
            assert_eq!(
                output
                    .descendants()
                    .filter(|n| n.has_tag_name("comClass"))
                    .count(),
                usize::from(selected)
            );
            assert_eq!(
                output
                    .descendants()
                    .filter(|n| n.has_tag_name("comInterfaceProxyStub"))
                    .count(),
                usize::from(selected)
            );
        }
        assert!(std::panic::catch_unwind(|| manifest(&classes, &doc, &BTreeSet::new())).is_err());
    }

    #[test]
    fn conflicting_classes_are_rejected() {
        let text = r#"<Fragment><InProcessServer><Path>Example.dll</Path>
            <ActivatableClass ActivatableClassId="Example.A" ThreadingModel="both"/>
            <ActivatableClass ActivatableClassId="Example.A" ThreadingModel="STA"/>
            </InProcessServer></Fragment>"#;
        assert!(std::panic::catch_unwind(|| read_classes(text, &mut Classes::new())).is_err());
    }
}
