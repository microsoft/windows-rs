use windows_bindgen::*;
use windows_clang::nuget_package;

const REACTOR_RDL: &str = "crates/tools/bindings/src/reactor.rdl";
const REACTOR_FILTER: &str = "crates/tools/bindings/src/reactor.txt";

fn main() {
    let time = std::time::Instant::now();

    bindgen(["--etc", "crates/tools/bindings/src/collections.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/core.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/cppwinrt.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/future_impl.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/future.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/metadata.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/numerics.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/registry.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/result.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/strings.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/version.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/threading.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/time.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/services.txt"]);

    bindgen(["--etc", "crates/tools/bindings/src/canvas.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/animation.txt"]);
    bindgen(["--etc", "crates/tools/bindings/src/window.txt"]);

    generate_reactor_bindings();

    // Reactor's behavior and control catalog are hand-written. This fixed ABI filter generates
    // only the private WinUI projection used by that implementation.
    // WebView2 bindings are generated by tool_webview.
    // Package crates (windows, windows-sys) are generated by tool_package.

    println!("Finished in {:.2}s", time.elapsed().as_secs_f32());
}

fn generate_reactor_bindings() {
    let output = std::path::Path::new("target/bindings");
    std::fs::create_dir_all(output).unwrap();

    let rdl = output.join("reactor.rdl");
    let winmd = output.join("reactor.winmd");
    std::fs::write(&rdl, reactor_rdl()).unwrap();
    windows_rdl::Reader::new()
        .input(&rdl)
        .reference_default()
        .output(&winmd)
        .write()
        .unwrap();

    let metadata = helpers::windows_app_sdk_metadata(nuget_package);
    refresh_reactor_bootstrap(metadata.foundation.parent().unwrap());
    let webview_version =
        helpers::read_str_const("crates/libs/reactor-setup/src/lib.rs", "WEBVIEW2_VER");
    let webview = nuget_package("microsoft.web.webview2", &webview_version)
        .join("lib")
        .join("Microsoft.Web.WebView2.Core.winmd");

    builder()
        .inputs([
            metadata.foundation,
            metadata.interactive,
            metadata.winui,
            webview,
            winmd,
        ])
        .input_default()
        .output("crates/libs/reactor/src/bindings.rs")
        .implements([
            "Microsoft.UI.Xaml.IApplicationOverrides",
            "Microsoft.UI.Xaml.Markup.IXamlMetadataProvider",
        ])
        .minimal()
        .dead_code()
        .flat()
        .filter_file(REACTOR_FILTER)
        .write();
}

fn reactor_rdl() -> String {
    let version = helpers::read_str_const("crates/libs/reactor-setup/src/lib.rs", "RUNTIME_VER");
    let parts = version
        .split('.')
        .map(|part| part.parse::<u64>().unwrap())
        .collect::<Vec<_>>();
    assert!(
        matches!(parts.as_slice(), [_, _, _] | [_, _, _, _]),
        "Windows App SDK runtime version must have three or four components"
    );
    let major = parts[0];
    let minor = parts[1];
    let build = parts[2];
    let revision = parts.get(3).copied().unwrap_or(0);
    let major_minor = (major << 16) | minor;
    let packed = (major << 48) | (minor << 32) | (build << 16) | revision;

    std::fs::read_to_string(REACTOR_RDL)
        .unwrap()
        .replace("@VERSION@", &version)
        .replace("@MAJOR@", &major.to_string())
        .replace("@MINOR@", &minor.to_string())
        .replace("@BUILD@", &build.to_string())
        .replace("@REVISION@", &revision.to_string())
        .replace("@MAJOR_MINOR@", &major_minor.to_string())
        .replace("@PACKED_VERSION@", &packed.to_string())
}

fn refresh_reactor_bootstrap(foundation: &std::path::Path) {
    const DLL: &str = "Microsoft.WindowsAppRuntime.Bootstrap.dll";
    for (arch, rid) in [
        ("arm64", "win-arm64"),
        ("x64", "win-x64"),
        ("x86", "win-x86"),
    ] {
        let source = foundation
            .join("runtimes")
            .join(rid)
            .join("native")
            .join(DLL);
        let destination = std::path::Path::new("crates/libs/reactor-setup/bootstrap").join(arch);
        std::fs::create_dir_all(&destination).unwrap();
        std::fs::copy(&source, destination.join(DLL)).unwrap_or_else(|error| {
            panic!(
                "failed to copy {} to {}: {error}",
                source.display(),
                destination.display()
            )
        });
    }
}
