use helpers::nuget_package;
use std::path::{Path, PathBuf};
use windows_metadata::merge;

/// The committed, canonical WinRT winmd. Checked in as `windows-bindgen`'s default WinRT
/// metadata (selected with `--in default`), so downstream filters resolve against a stable
/// in-repo winmd without re-running this tool. Re-derived from the pinned SDK Contracts
/// package on every run; treat it as generated output.
const WINMD: &str = "crates/libs/default/Windows.winmd";

/// Where the WinRT RDL snapshot is written (committed, human-reviewable), one file per
/// namespace (`Windows.Foundation.rdl`, `Windows.Globalization.rdl`, ...). The winmd above is
/// compiled from this committed RDL, so a WinRT metadata change produces a readable RDL
/// `git diff`. Regenerated by running this tool; treat it as generated output, not a place to
/// hand-edit.
const RDL_DIR: &str = "metadata/winrt";

/// Where the intermediate merged winmd is written before it is decompiled to RDL. Under
/// `target` and not tracked - regenerated on demand.
const OUT_DIR: &str = "target/winrt";

/// The NuGet package that ships the per-contract WinRT `.winmd` files.
const CONTRACTS_ID: &str = "microsoft.windows.sdk.contracts";

/// All contract files come from this release, independently of `tool-win32`'s SDK pin.
const CONTRACTS_VERSION: &str = "10.0.28000.2270";

/// The per-contract winmds live under this subtree in the package (`Windows.Foundation.winmd`,
/// `Windows.Globalization.winmd`, ...), one file per API contract.
const CONTRACTS_SUBDIR: &str = "ref/netstandard2.0";

fn main() {
    let time = std::time::Instant::now();

    let contracts_dir = nuget_package(CONTRACTS_ID, CONTRACTS_VERSION).join(CONTRACTS_SUBDIR);
    let inputs = contract_files(&contracts_dir);

    // Merge the per-contract winmds into one intermediate winmd, replacing the external
    // `mdmerge` tool with `windows-metadata`'s in-house merger (the same one `tool-win32`
    // uses). The per-contract WinRT runtime-class methods and Property/Event tables
    // are dropped by the merge; `windows-bindgen` reconstructs properties/events from the
    // surviving `get_`/`put_`/`add_`/`remove_` accessor methods on the interfaces and never
    // reads class methods.
    std::fs::create_dir_all(OUT_DIR)
        .unwrap_or_else(|e| panic!("failed to create `{OUT_DIR}`: {e}"));
    let merged = format!("{OUT_DIR}/Windows.merged.winmd");
    merge()
        .inputs(&inputs)
        .output(&merged)
        .merge()
        .unwrap_or_else(|e| panic!("failed to merge WinRT contracts into `{merged}`: {e}"));

    // Decompile the merged winmd into the committed per-namespace RDL snapshot, then compile
    // that snapshot back into the canonical `Windows.winmd`. This makes the RDL the source of
    // truth - consistent with `tool-win32`, which likewise scrapes to RDL and compiles
    // the winmd from it - and lets the `gen` `git diff` validate both the RDL and the winmd. The
    // WinRT surface is self-contained (`System.*` primitives are resolved by the reader), so the
    // reader needs no additional reference winmds; the `Win32` exclusion guards against any stray
    // references the merge might carry.
    windows_rdl::writer()
        .input(&merged)
        .filters(["Windows", "!Windows.Win32"])
        .split()
        .output(RDL_DIR)
        .write()
        .unwrap_or_else(|e| panic!("failed to write WinRT RDL to `{RDL_DIR}`: {e}"));

    windows_rdl::reader()
        .input(RDL_DIR)
        .output(WINMD)
        .write()
        .unwrap_or_else(|e| panic!("failed to compile `{WINMD}` from `{RDL_DIR}`: {e}"));

    println!(
        "generated `{RDL_DIR}` and `{WINMD}` from {} contract winmd(s) in {:.2}s",
        inputs.len(),
        time.elapsed().as_secs_f32()
    );
}

fn contract_files(dir: &Path) -> Vec<PathBuf> {
    let mut inputs = Vec::new();
    for entry in std::fs::read_dir(dir)
        .unwrap_or_else(|error| panic!("failed to read `{}`: {error}", dir.display()))
    {
        let path = entry
            .unwrap_or_else(|error| panic!("failed to enumerate `{}`: {error}", dir.display()))
            .path();
        if path
            .extension()
            .is_some_and(|extension| extension == "winmd")
        {
            assert!(
                path.is_file(),
                "expected a contract file: `{}`",
                path.display()
            );
            inputs.push(path);
        }
    }
    inputs.sort();
    assert!(
        !inputs.is_empty(),
        "no `.winmd` files found under `{}`",
        dir.display()
    );
    inputs
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir() -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "windows-rs-contracts-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir(&dir).unwrap();
        dir
    }

    #[test]
    fn contract_files_are_sorted_and_ignore_other_extensions() {
        let dir = temp_dir();
        for name in ["Windows.Z.winmd", "Windows.A.winmd", "readme.txt"] {
            std::fs::write(dir.join(name), "").unwrap();
        }
        std::fs::create_dir(dir.join("nested")).unwrap();
        assert_eq!(
            contract_files(&dir),
            [dir.join("Windows.A.winmd"), dir.join("Windows.Z.winmd")]
        );
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn rejects_missing_empty_and_invalid_contract_directories() {
        let dir = temp_dir();
        assert!(std::panic::catch_unwind(|| contract_files(&dir.join("missing"))).is_err());
        assert!(std::panic::catch_unwind(|| contract_files(&dir)).is_err());
        std::fs::create_dir(dir.join("NotAFile.winmd")).unwrap();
        assert!(std::panic::catch_unwind(|| contract_files(&dir)).is_err());
        std::fs::remove_dir_all(dir).unwrap();
    }
}
